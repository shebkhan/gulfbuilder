"use server";

import { renderToBuffer } from "@react-pdf/renderer";
import { can } from "@/lib/rbac";
import { createSupabaseServerClient } from "@/lib/supabase/server";
import { getOrgContext } from "@/server/org-context";
import { ContractPdf, type ContractPdfData } from "@/lib/pdf/contract";
import { storePdf } from "@/lib/pdf/storage";

export type ContractPdfState = { error?: string; url?: string };

export async function generateContractPdfAction(leaseId: string): Promise<ContractPdfState> {
  const ctx = await getOrgContext();
  if (!ctx || !can(ctx.role, "finance.read") && !can(ctx.role, "properties.read")) return { error: "not_authorised" };

  const supabase = await createSupabaseServerClient();
  const { data: lease } = await supabase
    .from("leases")
    .select("*, tenants(full_name), units(unit_no, buildings(name, code)), lease_terms(note, rent_minor, effective_from)")
    .eq("id", leaseId)
    .maybeSingle();
  if (!lease) return { error: "not_found" };

  const { data: branding } = await supabase
    .from("org_branding")
    .select("app_name")
    .eq("org_id", lease.org_id)
    .maybeSingle();

  const tenant = lease.tenants as unknown as { full_name: string } | null;
  const unit = lease.units as unknown as { unit_no: string; buildings: { name: string; code: string } | null } | null;
  const terms = (lease.lease_terms ?? []) as { note: string | null; rent_minor: number; effective_from: string }[];

  const data: ContractPdfData = {
    orgName: branding?.app_name ?? "Gulf Property",
    leaseNo: lease.lease_no,
    tenant: tenant?.full_name ?? "—",
    unit: [unit?.buildings?.name, unit?.unit_no].filter(Boolean).join(" / "),
    startDate: lease.start_date,
    endDate: lease.end_date,
    frequency: lease.payment_frequency,
    installments: lease.installments,
    dueDay: lease.due_day,
    noticeDays: lease.notice_days,
    registrationNo: lease.registration_no ?? null,
    rent: lease.rent_minor,
    deposit: lease.deposit_minor,
    currency: lease.currency,
    terms: terms.map((t) => ({ effectiveFrom: t.effective_from, rent: t.rent_minor, note: t.note })),
    footer: terms.find((t) => t.note)?.note ?? "Generated by Gulf Property",
  };

  const buffer = await renderToBuffer(<ContractPdf data={data} />);
  const result = await storePdf(ctx.supabase, ctx.orgId, ctx.userId, "contracts", "lease", leaseId, "contract", buffer);
  return result.url ? { url: result.url } : { error: result.error ?? "upload_failed" };
}