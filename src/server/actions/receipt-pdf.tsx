"use server";

import { renderToBuffer } from "@react-pdf/renderer";
import { revalidatePath } from "next/cache";
import { can } from "@/lib/rbac";
import { createSupabaseServerClient } from "@/lib/supabase/server";
import { getOrgContext } from "@/server/org-context";
import { ReceiptPdf, type ReceiptPdfData } from "@/lib/pdf/receipt";
import { storePdf } from "@/lib/pdf/storage";


export type ReceiptPdfState = { error?: string; url?: string };

export async function generateReceiptPdfAction(paymentId: string): Promise<ReceiptPdfState> {
  const ctx = await getOrgContext();
  if (!ctx || !can(ctx.role, "finance.read")) return { error: "not_authorised" };

  const supabase = await createSupabaseServerClient();
  const { data: payment } = await supabase
    .from("payments")
    .select("*, tenants(full_name), leases(lease_no)")
    .eq("id", paymentId)
    .maybeSingle();
  if (!payment) return { error: "not_found" };

  const { data: allocations } = await supabase
    .from("payment_allocations")
    .select("amount_minor, charges(type, due_date)")
    .eq("payment_id", paymentId);

  const { data: branding } = await supabase
    .from("org_branding")
    .select("app_name")
    .eq("org_id", payment.org_id)
    .maybeSingle();

  const tenant = payment.tenants as unknown as { full_name: string } | null;
  const lease = payment.leases as unknown as { lease_no: string } | null;

  const data: ReceiptPdfData = {
    orgName: branding?.app_name ?? "Gulf Property",
    receiptNo:
      payment.receipt_year && payment.receipt_no
        ? `${payment.receipt_year}/${payment.receipt_no}`
        : "Pending",
    tenant: tenant?.full_name ?? "—",
    lease: lease?.lease_no ?? null,
    method: payment.method,
    date: payment.received_at.slice(0, 10),
    reference: payment.reference ?? null,
    amount: payment.amount_minor,
    currency: payment.currency,
    allocations: (allocations ?? []).map((a: any) => {
      const charge = a.charges as { type: string; due_date: string } | null;
      return {
        label: charge?.type ?? "allocation",
        detail: charge?.due_date,
        amount: a.amount_minor,
      };
    }),
    footer: "Generated by Gulf Property",
  };

  const buffer = await renderToBuffer(<ReceiptPdf data={data} />);
  revalidatePath("/payments");
  const result = await storePdf(ctx.supabase, ctx.orgId, ctx.userId, "receipts", "payment", paymentId, "receipt", buffer);
  return result.url ? { url: result.url } : { error: result.error ?? "upload_failed" };
}